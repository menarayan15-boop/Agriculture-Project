// Localized helper functions
export function getCropDisplayName(cropOrId, lang = 'en') {
  if (!cropOrId) return '';
  const cropId = typeof cropOrId === 'string' 
    ? cropOrId.toLowerCase().replace('crop-', '').replace('-desc', '')
    : (cropOrId.id || '').toLowerCase();

  // 1. Direct dictionary match
  if (CROP_LOCALIZED_NAMES[cropId] && CROP_LOCALIZED_NAMES[cropId][lang]) {
    return CROP_LOCALIZED_NAMES[cropId][lang];
  }

  // 2. Fuzzy match by partial key
  for (const [key, trans] of Object.entries(CROP_LOCALIZED_NAMES)) {
    if (cropId.includes(key) || (typeof cropOrId === 'object' && (cropOrId.name || '').toLowerCase().includes(key))) {
      if (trans[lang]) return trans[lang];
    }
  }

  // 3. Fallback to object properties
  if (typeof cropOrId === 'object') {
    if (lang === 'hi' && (cropOrId.hindiName || cropOrId.nameHi)) return cropOrId.hindiName || cropOrId.nameHi;
    if (cropOrId.nameKey) {
      const text = getText(cropOrId.nameKey, lang);
      if (text && text !== cropOrId.nameKey) return text;
    }
    return cropOrId.name || cropOrId.nameEn || cropId;
  }

  return cropId;
}

export function getCategoryDisplayName(cat, lang = 'en') {
  if (!cat) return '';
  const key = cat.toLowerCase().trim();
  if (CATEGORY_LOCALIZED_NAMES[key] && CATEGORY_LOCALIZED_NAMES[key][lang]) {
    return CATEGORY_LOCALIZED_NAMES[key][lang];
  }
  for (const [k, trans] of Object.entries(CATEGORY_LOCALIZED_NAMES)) {
    if (key.includes(k) && trans[lang]) return trans[lang];
  }
  return cat;
}

export function getText(key, lang = 'en') {
  if (TRANSLATIONS[lang] && TRANSLATIONS[lang][key]) return TRANSLATIONS[lang][key];
  if (TRANSLATIONS.en && TRANSLATIONS.en[key]) return TRANSLATIONS.en[key];

  // Fallback for crop keys
  if (key && typeof key === 'string' && key.startsWith('crop-')) {
    const cropId = key.replace('crop-', '').replace('-desc', '').replace('-tips', '');
    const localized = getCropDisplayName(cropId, lang);
    if (localized && localized !== cropId) return localized;
  }

  // Formatting fallback for hyphenated keys instead of raw key
  if (key && typeof key === 'string' && key.includes('-')) {
    return key.split('-').map(w => w.charAt(0).toUpperCase() + w.slice(1)).join(' ');
  }

  return key;
}

